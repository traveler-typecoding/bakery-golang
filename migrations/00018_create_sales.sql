-- Sales / POS.
CREATE TABLE sales.sales (
    id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    client_uuid     uuid NOT NULL UNIQUE,       -- generated by the POS device; makes offline sync idempotent
    outlet_id       bigint NOT NULL REFERENCES org.outlets(id),
    receipt_no      text NOT NULL,
    customer_id     bigint REFERENCES sales.customers(id),
    cashier_id      bigint NOT NULL REFERENCES auth.users(id),
    status          text NOT NULL DEFAULT 'completed'
                    CHECK (status IN ('open','completed','void','refunded')),
    subtotal        numeric(18,2) NOT NULL,
    discount_total  numeric(18,2) NOT NULL DEFAULT 0,
    tax_total       numeric(18,2) NOT NULL DEFAULT 0,
    grand_total     numeric(18,2) NOT NULL,
    sold_at         timestamptz NOT NULL,       -- device time of sale
    synced_at       timestamptz NOT NULL DEFAULT now(),
    UNIQUE (outlet_id, receipt_no)
);
CREATE INDEX idx_sales_outlet_date ON sales.sales(outlet_id, sold_at);

